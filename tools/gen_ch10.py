import json, sys
CH = "Chapter 10 · Planning the Pesticide Application"
cards = []

def card(n, title, pages, body, figures, questions):
    sid = f"c10-s{n:02d}"
    r = t = 0
    qs = []
    for q in questions:
        q = dict(q)
        if q["src"] == "review":
            r += 1; q["id"] = f"{sid}-r{r}"
        else:
            t += 1; q["id"] = f"{sid}-t{t}"
        qs.append({"id": q.pop("id"), **q})
    cards.append({"id": sid, "chapter": CH, "title": title, "pages": pages, "body": body, "figures": figures, "questions": qs})

def R(num, page, q, choices, answer, textref, why):
    return {"src": "review", "kind": "mc", "q": q, "choices": choices, "answer": answer,
            "ref": f"Review question {num}, p. {page}. Answer in the text: {textref}", "why": why}

def MC(q, choices, ref, why, style=None, answer=0):
    d = {"src": "test", "kind": "mc"}
    if style: d["style"] = style
    d.update({"q": q, "choices": choices, "answer": answer, "ref": ref, "why": why})
    return d

def TF(q, answer, ref, why):
    return {"src": "test", "kind": "tf", "q": q, "answer": answer, "ref": ref, "why": why}

def img(fid, title, page):
    return {"id": fid, "title": title, "page": page, "imgFile": fid + ".jpg"}

